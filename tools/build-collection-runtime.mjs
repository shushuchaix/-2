import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";
const project = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
function run(executable, args, { env = process.env } = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, {
      cwd: project,
      env,
      windowsHide: true,
      shell: false,
      stdio: "inherit",
    });
    child.once("error", reject);
    child.once("exit", (code) =>
      code === 0
        ? resolve()
        : reject(Error("Runtime build command failed: " + code)),
    );
  });
}
async function files(root, dir = root) {
  const out = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    if (dir === root && entry.name === "build-cache") continue;
    const abs = path.join(dir, entry.name);
    if (entry.isSymbolicLink()) throw Error("Runtime link forbidden");
    if (entry.isDirectory()) out.push(...(await files(root, abs)));
    else if (entry.isFile())
      out.push({
        path: path.relative(root, abs).replaceAll("\\", "/"),
        bytes: (await fs.stat(abs)).size,
        sha256: sha(await fs.readFile(abs)),
      });
  }
  return out;
}
export async function buildCollectionRuntime({
  destination = path.join(project, ".cache/collection-runtime-dev"),
  manifest,
  platform = process.platform,
  arch = process.arch,
  uvPath = path.join(process.env.USERPROFILE, ".local/bin/uv.exe"),
  lock = false,
} = {}) {
  if (platform !== "win32" || arch !== "x64")
    throw Error("Runtime build supports Windows x64");
  const root = path.resolve(destination),
    cacheRoot = path.join(project, ".cache");
  if (!root.startsWith(cacheRoot + path.sep))
    throw Error("Build destination must be inside project .cache");
  manifest ||= JSON.parse(
    await fs.readFile(
      path.join(project, "resources/collection-runtime/manifest.json"),
      "utf8",
    ),
  );
  const pythonDir = path.join(root, "python"),
    python = path.join(pythonDir, "python.exe"),
    buildCache = path.join(root, "build-cache");
  await fs.mkdir(pythonDir, { recursive: true });
  await fs.mkdir(buildCache, { recursive: true });
  try {
    await fs.access(python);
  } catch {
    const zip = path.join(buildCache, "python.zip");
    let bytes;
    try {
      bytes = await fs.readFile(zip);
    } catch {
      const response = await fetch(manifest.python.url);
      if (!response.ok)
        throw Error("Official Python download failed: " + response.status);
      bytes = Buffer.from(await response.arrayBuffer());
    }
    if (bytes.length > 40000000 || sha(bytes) !== manifest.python.sha256)
      throw Error("Python distribution hash mismatch");
    await fs.writeFile(zip, bytes);
    await run(path.join(process.env.SystemRoot, "System32/tar.exe"), [
      "-xf",
      zip,
      "-C",
      pythonDir,
    ]);
  }
  await fs.writeFile(
    path.join(pythonDir, "python314._pth"),
    "python314.zip\n.\nLib/site-packages\nimport site\n",
  );
  const common = ["--no-config", "pip"],
    target = [
      "--python",
      python,
      "--python-platform",
      "x86_64-pc-windows-msvc",
      "--only-binary",
      ":all:",
      "--no-python-downloads",
      "--cache-dir",
      path.join(buildCache, "uv"),
      "--default-index",
      "https://pypi.org/simple",
    ],
    lockfile = path.join(project, "python/requirements.lock");
  if (lock) {
    await run(uvPath, [
      ...common,
      "compile",
      path.join(project, "python/requirements.in"),
      ...target,
      "--python-version",
      "3.14.8",
      "--generate-hashes",
      "--output-file",
      lockfile,
    ]);
  }
  await fs.writeFile(
    lockfile,
    (await fs.readFile(lockfile, "utf8")).replace(
      /^# This file was autogenerated[^\n]*\n#\s*uv[^\n]*\n/,
      "# Generated by tools/build-collection-runtime.mjs for Python 3.14.8 Windows x64.\n",
    ),
  );
  await run(uvPath, [
    ...common,
    "install",
    ...target,
    "--target",
    path.join(pythonDir, "Lib/site-packages"),
    "--require-hashes",
    "--link-mode",
    "copy",
    "--requirements",
    lockfile,
  ]);
  const env = {
    ...process.env,
    PLAYWRIGHT_BROWSERS_PATH: path.join(root, "browsers"),
    PLAYWRIGHT_SKIP_BROWSER_GC: "1",
  };
  delete env.PYTHONPATH;
  delete env.PYTHONHOME;
  for (const module of ["playwright", "patchright"])
    await run(
      python,
      ["-I", "-B", "-m", module, "install", "chromium", "--no-shell"],
      { env },
    );
  await fs.mkdir(path.join(root, "worker"), { recursive: true });
  await fs.copyFile(
    path.join(project, "python/collection_worker.py"),
    path.join(root, "worker/collection_worker.py"),
  );
  const actual = JSON.parse(JSON.stringify(manifest));
  await fs.copyFile(
    path.join(project, "resources/collection-runtime/THIRD-PARTY-NOTICES.md"),
    path.join(root, "THIRD-PARTY-NOTICES.md"),
  );
  actual.browsers = {};
  for (const module of ["playwright", "patchright"]) {
    const data = JSON.parse(
      await fs.readFile(
        path.join(
          pythonDir,
          "Lib/site-packages",
          module,
          "driver/package/browsers.json",
        ),
        "utf8",
      ),
    );
    actual.browsers[module] = data.browsers.filter(
      (b) => b.name === "chromium",
    );
    if (
      actual.browsers[module][0]?.revision !==
        manifest.browsers[module][0].revision ||
      actual.browsers[module][0]?.browserVersion !==
        manifest.browsers[module][0].browserVersion
    )
      throw Error("Browser lock does not match actual driver");
  }
  actual.files = (await files(root)).filter(
    (f) => !f.path.startsWith("build-cache/") && f.path !== "manifest.json",
  );
  actual.licenses = actual.files
    .filter((f) => /(?:license|copying|notice)(?:\.|\/|$)/i.test(f.path))
    .map((f) => f.path);
  await fs.writeFile(
    path.join(root, "manifest.json"),
    JSON.stringify(actual, null, 2) + "\n",
  );
  return { root, files: actual.files.length, browsers: actual.browsers };
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  console.log(
    JSON.stringify(
      await buildCollectionRuntime({ lock: process.argv.includes("--lock") }),
    ),
  );
